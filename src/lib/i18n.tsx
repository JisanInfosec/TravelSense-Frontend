let currentLang: Lang = "en";

const LangContext = createContext<{ lang: Lang; setLang: (l: Lang) => void; t: (key: string, params?: Record<string, string | number>) => string } | null>(null);

export function LanguageProvider({ children, defaultLang = "en" }: { children: React.ReactNode; defaultLang?: Lang }) {
  const [lang, setLangState] = useState<Lang>(defaultLang);

  useEffect(() => {
    try {
      const stored = localStorage.getItem(STORAGE_KEY) as Lang | null;
      // Loading a user preference is an intentional one-time client sync after hydration.
      // eslint-disable-next-line react-hooks/set-state-in-effect
      if (stored === "en" || stored === "bn") setLangState(stored);
    } catch {}
  }, []);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch {}
    document.documentElement.lang = l === "bn" ? "bn" : "en";
  }, []);

  useEffect(() => {
    currentLang = lang;
    document.documentElement.lang = lang === "bn" ? "bn" : "en";
  }, [lang]);

  const t = useCallback((key: string, params: Record<string, string | number> = {}) => {
    const parts = key.split(".");
    let node: unknown = (ALL as Record<string, Record<Lang, unknown>>)[parts[0]]?.[lang];
    for (let i = 1; i < parts.length; i++) {
      if (!node || typeof node !== "object") {
        node = undefined;
        break;
      }
      node = (node as Record<string, unknown>)[parts[i]];
    }
    let str = typeof node === "string" ? node : key;
    str = str.replace(/\{(\w+)\}/g, (_, k) => {
      const v = params[k];
      if (typeof v === "number") return String(v);
      return String(v ?? "");
    });
    // handle simple plural ternaries like {total === 1 ? 'a' : 'b'} crudely
    str = str.replace(/\{\s*(\w+)\s*===\s*1\s*\?\s*'([^']*)'\s*:\s*'([^']*)'\s*\}/g, (_, k, a, b) => {
      const v = params[k];
      return typeof v === "number" ? (v === 1 ? a : b) : b;
    });
    return str;
  }, [lang]);

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);
  return <LangContext.Provider value={value}>{children}</LangContext.Provider>;
}

export function useTranslation() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useTranslation must be used inside <LanguageProvider>");
  return ctx;
}

export function getLang(): Lang {
  return currentLang;
}

